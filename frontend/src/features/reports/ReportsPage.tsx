import { keepPreviousData, useQuery } from '@tanstack/react-query'
import { useSearchParams } from 'react-router'
import { useApiClient } from '../../api/context'
import type { ExecutionListItem, ExecutionStatus } from '../../api/executions'
import { executionQueries } from '../../api/queries'
import { QuerySection } from '../../components/QuerySection'
import {
    Button,
    Card,
    EmptyState,
    PageHeader,
    Select,
    TextLink,
    type TableColumn,
} from '../../components/ui'
import { executionStatusDisplay } from '../dashboard/format'
import { ExecutionTable } from '../executions/shared'
import { reportPath } from '../executions/format'

const PAGE_SIZE = 25

// A report exists for every execution, but only a finished one is final;
// running ones stay reachable from their inspector.
const FINISHED = [
    'completed',
    'failed',
    'timeout',
    'cancelled',
] as const satisfies readonly ExecutionStatus[]
type Finished = (typeof FINISHED)[number]
const isFinished = (v: string | null): v is Finished =>
    (FINISHED as readonly (string | null)[]).includes(v)

const reportColumn: TableColumn<ExecutionListItem> = {
    key: 'report',
    header: <span className="sr-only">Report</span>,
    align: 'end',
    cell: (e) => (
        <TextLink
            to={reportPath(e.id)}
            aria-label={`View report of execution ${e.id}`}
        >
            View report
        </TextLink>
    ),
}

export function ReportsPage() {
    const [search, setSearch] = useSearchParams()
    const raw = search.get('status')
    const status = isFinished(raw) ? raw : null
    const offset = Math.max(0, Math.trunc(Number(search.get('offset'))) || 0)
    const update = (next: { status: Finished | null; offset: number }) => {
        const params = new URLSearchParams()
        if (next.status) params.set('status', next.status)
        if (next.offset > 0) params.set('offset', String(next.offset))
        setSearch(params)
    }
    const query = useQuery({
        ...executionQueries.list(useApiClient(), {
            status: status ? [status] : FINISHED,
            offset,
            limit: PAGE_SIZE,
        }),
        placeholderData: keepPreviousData,
    })
    return (
        <>
            <PageHeader
                title="Reports"
                description="Execution reports of finished runs, newest first. Generated by the backend from persisted state; secrets are redacted."
                actions={
                    <Button
                        loading={query.isFetching}
                        onClick={() => void query.refetch()}
                    >
                        Refresh
                    </Button>
                }
            />
            <Card>
                <div className="mb-4 max-w-xs">
                    <Select
                        label="Status"
                        value={status ?? ''}
                        onChange={(event) => {
                            const v = event.target.value
                            update({
                                status: isFinished(v) ? v : null,
                                offset: 0,
                            })
                        }}
                    >
                        <option value="">All finished</option>
                        {FINISHED.map((s) => (
                            <option key={s} value={s}>
                                {executionStatusDisplay[s].label}
                            </option>
                        ))}
                    </Select>
                </div>
                <QuerySection query={query} subject="reports">
                    {({ items, page }) =>
                        items.length === 0 && offset === 0 ? (
                            <EmptyState
                                title="No reports yet"
                                titleAs="h2"
                                description={
                                    status
                                        ? `No execution is ${executionStatusDisplay[status].label.toLowerCase()}.`
                                        : 'A report appears here once an execution finishes.'
                                }
                                action={
                                    <TextLink to="/executions">
                                        Go to executions
                                    </TextLink>
                                }
                            />
                        ) : (
                            <div
                                aria-busy={query.isPlaceholderData || undefined}
                            >
                                <ExecutionTable
                                    caption="Reports"
                                    executions={items}
                                    extraColumns={[reportColumn]}
                                />
                                <nav
                                    aria-label="Report pages"
                                    className="mt-3 flex justify-end gap-2"
                                >
                                    <Button
                                        size="sm"
                                        disabled={offset === 0}
                                        onClick={() => {
                                            update({
                                                status,
                                                offset: Math.max(
                                                    0,
                                                    offset - PAGE_SIZE,
                                                ),
                                            })
                                        }}
                                    >
                                        Previous
                                    </Button>
                                    <Button
                                        size="sm"
                                        disabled={!page.has_more}
                                        onClick={() => {
                                            update({
                                                status,
                                                offset: offset + PAGE_SIZE,
                                            })
                                        }}
                                    >
                                        Next
                                    </Button>
                                </nav>
                            </div>
                        )
                    }
                </QuerySection>
            </Card>
        </>
    )
}

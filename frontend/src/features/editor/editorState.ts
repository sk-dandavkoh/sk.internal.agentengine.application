import type {
    Edge,
    Graph,
    NodeInstance,
    NodePosition,
} from '../../api/workflows'
import type { JsonObject } from '../../api/schemas'
import { randomHex } from '../../lib/randomHex'
import { edgeKey, sameEdge } from './graphView'

// Editor state of one workflow draft (frontend/AGENTS §29). Pure: the hook
// in useDraftEditor.ts owns persistence; the canvas owns rendering-only
// state (measured sizes, viewport).
//
// Graphs are immutable values. Dirty tracking is by identity: `graph !==
// saved`, so undoing back to the saved graph makes the draft clean again.

export interface Clipboard {
    nodes: NodeInstance[]
    /** Only edges between copied nodes. */
    edges: Edge[]
}

export interface EditorState {
    /** The local, possibly unsaved draft graph. */
    graph: Graph
    /** The graph the server's draft holds (as of `revision`). */
    saved: Graph
    /** Draft revision `saved` belongs to; sent as `expected_revision`. */
    revision: number
    past: Graph[]
    future: Graph[]
    /** Selected node ids. Not part of undo history. */
    selection: string[]
    /** Selected edges, by `edgeKey`. Not part of undo history. */
    edgeSelection: string[]
    clipboard: Clipboard | null
    /** Graph before the drag in progress; one drag is one undo step. */
    dragOrigin: Graph | null
    /** `configure` field the last undo step belongs to; typing on in that
     * field extends the step instead of adding one per keystroke. */
    lastEdit: string | null
}

export type EditorAction =
    | {
          type: 'move'
          positions: Readonly<Record<string, NodePosition>>
          /** false while dragging, true when the drag ends. */
          done: boolean
      }
    /** An omitted kind keeps its selection. */
    | { type: 'select'; nodeIds?: string[]; edgeKeys?: string[] }
    | { type: 'undo' }
    | { type: 'redo' }
    | { type: 'copy' }
    /** New ids for the clipboard's nodes, generated by the caller. */
    | { type: 'paste'; ids: Readonly<Record<string, string>> }
    /** A new node, built by the caller (fresh id, catalog type). */
    | { type: 'add'; node: NodeInstance }
    /** Copies of the selected nodes; new ids generated by the caller. */
    | { type: 'duplicate'; ids: Readonly<Record<string, string>> }
    /** Nodes (with every edge they touch) and edges, as one step. */
    | {
          type: 'delete'
          nodeIds: readonly string[]
          edgeKeys: readonly string[]
      }
    /** Whether the ports fit is checked by the caller (connections.ts);
     * the reducer only refuses what would make the draft unsavable. */
    | { type: 'connect'; edge: Edge }
    /** `from`, moved to other ports; it keeps its place in the edge list. */
    | { type: 'reconnect'; from: Edge; edge: Edge }
    /** The server stored `graph` as `revision`. */
    | { type: 'saved'; graph: Graph; revision: number }
    /** A node's whole new config, edited through `field` (a top-level
     * config key). Validity is the backend's call, not the reducer's. */
    | { type: 'configure'; nodeId: string; config: JsonObject; field: string }

// ponytail: fixed cap; make it a preference if users ask for deeper history.
export const HISTORY_LIMIT = 100
export const PASTE_OFFSET = 40
const COLUMN_GAP = 280
const ROW_GAP = 140

export function initEditor(graph: Graph, revision: number): EditorState {
    const placed = placeUnpositioned(graph)
    return {
        graph: placed,
        // Layout of never-placed nodes is not a user change: it is saved
        // along with the next real edit (docs/architecture.md §7.2).
        saved: placed,
        revision,
        past: [],
        future: [],
        selection: [],
        edgeSelection: [],
        clipboard: null,
        dragOrigin: null,
        lastEdit: null,
    }
}

export const isDirty = (state: EditorState) => state.graph !== state.saved

/** Columns by longest path from a source, rows in graph order. */
export function placeUnpositioned(graph: Graph): Graph {
    if (graph.nodes.every((n) => n.position !== null)) return graph
    const depth = new Map(graph.nodes.map((n) => [n.id, 0]))
    // ponytail: O(V·E) relaxation, capped at V rounds so cycles terminate;
    // fine for drafts of hundreds of nodes, use a topological sort if not.
    let rounds = graph.nodes.length
    let changed = true
    while (changed && rounds-- > 0) {
        changed = false
        for (const e of graph.edges) {
            const next = (depth.get(e.source_node_id) ?? 0) + 1
            if (
                depth.has(e.target_node_id) &&
                next > (depth.get(e.target_node_id) ?? 0)
            ) {
                depth.set(e.target_node_id, next)
                changed = true
            }
        }
    }
    const rows = new Map<number, number>()
    // Placed nodes keep their position; new ones go below everything.
    const top = Math.max(
        0,
        ...graph.nodes.map((n) => (n.position ? n.position.y + ROW_GAP : 0)),
    )
    return {
        ...graph,
        nodes: graph.nodes.map((n) => {
            if (n.position) return n
            const column = depth.get(n.id) ?? 0
            const row = rows.get(column) ?? 0
            rows.set(column, row + 1)
            return {
                ...n,
                position: { x: column * COLUMN_GAP, y: top + row * ROW_GAP },
            }
        }),
    }
}

function commit(
    state: EditorState,
    graph: Graph,
    from = state.graph,
): EditorState {
    return {
        ...state,
        graph,
        past: [...state.past, from].slice(-HISTORY_LIMIT),
        future: [],
        lastEdit: null,
    }
}

function withPositions(
    graph: Graph,
    positions: Readonly<Record<string, NodePosition>>,
): Graph {
    const nodes = graph.nodes.map((n) => {
        const p = positions[n.id]
        if (!p || (n.position?.x === p.x && n.position.y === p.y)) return n
        return { ...n, position: { x: p.x, y: p.y } }
    })
    return nodes.some((n, i) => n !== graph.nodes[i])
        ? { ...graph, nodes }
        : graph
}

export function editorReducer(
    state: EditorState,
    action: EditorAction,
): EditorState {
    switch (action.type) {
        case 'move': {
            const graph = withPositions(state.graph, action.positions)
            const origin = state.dragOrigin ?? state.graph
            if (!action.done)
                return graph === state.graph
                    ? state
                    : { ...state, graph, dragOrigin: origin }
            const next = { ...state, dragOrigin: null }
            // A drag that ends where it started is no edit.
            if (samePositions(graph, origin)) return { ...next, graph: origin }
            return commit(next, graph, origin)
        }
        case 'select':
            return {
                ...state,
                selection: action.nodeIds ?? state.selection,
                edgeSelection: action.edgeKeys ?? state.edgeSelection,
                lastEdit: null,
            }
        case 'undo': {
            const previous = state.past.at(-1)
            if (!previous || state.dragOrigin) return state
            return {
                ...state,
                graph: previous,
                past: state.past.slice(0, -1),
                future: [state.graph, ...state.future],
                ...existing(state, previous),
                lastEdit: null,
            }
        }
        case 'redo': {
            const next = state.future[0]
            if (!next || state.dragOrigin) return state
            return {
                ...state,
                graph: next,
                past: [...state.past, state.graph],
                future: state.future.slice(1),
                ...existing(state, next),
                lastEdit: null,
            }
        }
        case 'copy': {
            const clipboard = copyOf(state)
            return clipboard ? { ...state, clipboard } : state
        }
        case 'paste': {
            const clip = state.clipboard
            if (!clip || state.dragOrigin) return state
            const [next, copies] = insertCopies(state, clip, action.ids)
            // Pasting again lands one offset further, not on top.
            return { ...next, clipboard: copies }
        }
        case 'duplicate': {
            const clip = copyOf(state)
            if (!clip || state.dragOrigin) return state
            return insertCopies(state, clip, action.ids)[0]
        }
        case 'delete': {
            if (state.dragOrigin) return state
            const nodeIds = new Set(action.nodeIds)
            const edgeKeys = new Set(action.edgeKeys)
            const graph = {
                nodes: state.graph.nodes.filter((n) => !nodeIds.has(n.id)),
                edges: state.graph.edges.filter(
                    (e) =>
                        !edgeKeys.has(edgeKey(e)) &&
                        !nodeIds.has(e.source_node_id) &&
                        !nodeIds.has(e.target_node_id),
                ),
            }
            if (
                graph.nodes.length === state.graph.nodes.length &&
                graph.edges.length === state.graph.edges.length
            )
                return state
            return { ...commit(state, graph), ...existing(state, graph) }
        }
        case 'connect': {
            if (state.dragOrigin || !savable(state.graph, action.edge))
                return state
            return commit(state, {
                ...state.graph,
                edges: [...state.graph.edges, action.edge],
            })
        }
        case 'reconnect': {
            const { from, edge } = action
            const index = state.graph.edges.findIndex((e) => sameEdge(e, from))
            if (state.dragOrigin || index < 0 || sameEdge(from, edge))
                return state
            const rest = {
                ...state.graph,
                edges: state.graph.edges.filter((_, i) => i !== index),
            }
            if (!savable(rest, edge)) return state
            const edges = state.graph.edges.with(index, edge)
            return {
                ...commit(state, { ...state.graph, edges }),
                edgeSelection: state.edgeSelection.map((k) =>
                    k === edgeKey(from) ? edgeKey(edge) : k,
                ),
            }
        }
        case 'add': {
            // A reused id would make the draft unsavable (the backend
            // rejects duplicate node ids), so it is refused, not stored.
            if (
                state.dragOrigin ||
                state.graph.nodes.some((n) => n.id === action.node.id)
            )
                return state
            const node = {
                ...action.node,
                position:
                    action.node.position &&
                    freeSpot(state.graph, action.node.position),
            }
            return {
                ...commit(state, {
                    ...state.graph,
                    nodes: [...state.graph.nodes, node],
                }),
                selection: [node.id],
                edgeSelection: [],
            }
        }
        case 'configure': {
            const node = state.graph.nodes.find((n) => n.id === action.nodeId)
            if (!node || state.dragOrigin) return state
            const graph = {
                ...state.graph,
                nodes: state.graph.nodes.map((n) =>
                    n === node ? { ...n, config: action.config } : n,
                ),
            }
            const edit = `${action.nodeId} ${action.field}`
            if (state.lastEdit === edit) return { ...state, graph }
            return { ...commit(state, graph), lastEdit: edit }
        }
        case 'saved':
            // The undo stack survives a save (frontend/AGENTS §30).
            return { ...state, saved: action.graph, revision: action.revision }
    }
}

/** `p`, moved diagonally until no node sits exactly there, so repeated
 * adds at one spot stay visible instead of stacking. */
function freeSpot(graph: Graph, p: NodePosition): NodePosition {
    const taken = new Set(
        graph.nodes.map(
            (n) =>
                n.position && `${String(n.position.x)},${String(n.position.y)}`,
        ),
    )
    let { x, y } = p
    while (taken.has(`${String(x)},${String(y)}`)) {
        x += PASTE_OFFSET
        y += PASTE_OFFSET
    }
    return { x, y }
}

// Moves only change positions, so the node lists align index by index.
const samePositions = (a: Graph, b: Graph) =>
    a.nodes.every((n, i) => {
        const other = b.nodes[i]?.position
        return n.position?.x === other?.x && n.position?.y === other?.y
    })

/** The selection, minus what `graph` no longer has. */
function existing(state: EditorState, graph: Graph) {
    const edges = new Set(graph.edges.map(edgeKey))
    return {
        selection: state.selection.filter((id) =>
            graph.nodes.some((n) => n.id === id),
        ),
        edgeSelection: state.edgeSelection.filter((k) => edges.has(k)),
    }
}

/** The selected nodes plus the edges between them; null if none. */
function copyOf(state: EditorState): Clipboard | null {
    const ids = new Set(state.selection)
    if (ids.size === 0) return null
    return {
        nodes: state.graph.nodes.filter((n) => ids.has(n.id)),
        edges: state.graph.edges.filter(
            (e) => ids.has(e.source_node_id) && ids.has(e.target_node_id),
        ),
    }
}

/** `clip`'s nodes and edges under the new `ids`, offset, as one step and
 * the new selection; also returns the inserted copies. */
function insertCopies(
    state: EditorState,
    clip: Clipboard,
    ids: Readonly<Record<string, string>>,
): [EditorState, Clipboard] {
    const id = (old: string) => {
        const fresh = ids[old]
        if (fresh === undefined) throw new Error(`no id for ${old}`)
        return fresh
    }
    const shift = (p: NodePosition | null) =>
        p && { x: p.x + PASTE_OFFSET, y: p.y + PASTE_OFFSET }
    const nodes = clip.nodes.map((n) => ({
        ...n,
        id: id(n.id),
        position: shift(n.position),
    }))
    const edges = clip.edges.map((e) => ({
        ...e,
        source_node_id: id(e.source_node_id),
        target_node_id: id(e.target_node_id),
    }))
    const graph = {
        nodes: [...state.graph.nodes, ...nodes],
        edges: [...state.graph.edges, ...edges],
    }
    return [
        {
            ...commit(state, graph),
            selection: nodes.map((n) => n.id),
            edgeSelection: [],
        },
        { nodes, edges },
    ]
}

/** What the backend's PUT refuses outright: self-edges, duplicates and
 * dangling ends (domain `Edge`/`Graph.add_edge`). */
const savable = (graph: Graph, edge: Edge) =>
    edge.source_node_id !== edge.target_node_id &&
    [edge.source_node_id, edge.target_node_id].every((id) =>
        graph.nodes.some((n) => n.id === id),
    ) &&
    !graph.edges.some((e) => sameEdge(e, edge))

/** A backend-shaped node id (`node_` + 32 hex digits). */
export const newNodeId = () => `node_${randomHex()}`

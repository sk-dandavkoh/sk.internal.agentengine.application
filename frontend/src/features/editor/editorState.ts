import type {
    Edge,
    Graph,
    NodeInstance,
    NodePosition,
} from '../../api/projects'

// Editor state of one project draft (frontend/AGENTS §29). Pure: the hook
// in useDraftEditor.ts owns persistence; the canvas owns rendering-only
// state (measured sizes, viewport).
//
// Graphs are immutable values. Dirty tracking is by identity: `graph !==
// saved`, so undoing back to the saved graph makes the draft clean again.

export interface Clipboard {
    nodes: NodeInstance[]
    /** Only edges between copied nodes. */
    edges: Edge[]
}

export interface EditorState {
    /** The local, possibly unsaved draft graph. */
    graph: Graph
    /** The graph the server's draft holds (as of `revision`). */
    saved: Graph
    /** Draft revision `saved` belongs to; sent as `expected_revision`. */
    revision: number
    past: Graph[]
    future: Graph[]
    /** Selected node ids. Not part of undo history. */
    selection: string[]
    clipboard: Clipboard | null
    /** Graph before the drag in progress; one drag is one undo step. */
    dragOrigin: Graph | null
}

export type EditorAction =
    | {
          type: 'move'
          positions: Readonly<Record<string, NodePosition>>
          /** false while dragging, true when the drag ends. */
          done: boolean
      }
    | { type: 'select'; nodeIds: string[] }
    | { type: 'undo' }
    | { type: 'redo' }
    | { type: 'copy' }
    /** New ids for the clipboard's nodes, generated by the caller. */
    | { type: 'paste'; ids: Readonly<Record<string, string>> }
    /** The server stored `graph` as `revision`. */
    | { type: 'saved'; graph: Graph; revision: number }

// ponytail: fixed cap; make it a preference if users ask for deeper history.
export const HISTORY_LIMIT = 100
export const PASTE_OFFSET = 40
const COLUMN_GAP = 280
const ROW_GAP = 140

export function initEditor(graph: Graph, revision: number): EditorState {
    const placed = placeUnpositioned(graph)
    return {
        graph: placed,
        // Layout of never-placed nodes is not a user change: it is saved
        // along with the next real edit (docs/architecture.md §7.2).
        saved: placed,
        revision,
        past: [],
        future: [],
        selection: [],
        clipboard: null,
        dragOrigin: null,
    }
}

export const isDirty = (state: EditorState) => state.graph !== state.saved

/** Columns by longest path from a source, rows in graph order. */
export function placeUnpositioned(graph: Graph): Graph {
    if (graph.nodes.every((n) => n.position !== null)) return graph
    const depth = new Map(graph.nodes.map((n) => [n.id, 0]))
    // ponytail: O(V·E) relaxation, capped at V rounds so cycles terminate;
    // fine for drafts of hundreds of nodes, use a topological sort if not.
    let rounds = graph.nodes.length
    let changed = true
    while (changed && rounds-- > 0) {
        changed = false
        for (const e of graph.edges) {
            const next = (depth.get(e.source_node_id) ?? 0) + 1
            if (
                depth.has(e.target_node_id) &&
                next > (depth.get(e.target_node_id) ?? 0)
            ) {
                depth.set(e.target_node_id, next)
                changed = true
            }
        }
    }
    const rows = new Map<number, number>()
    // Placed nodes keep their position; new ones go below everything.
    const top = Math.max(
        0,
        ...graph.nodes.map((n) => (n.position ? n.position.y + ROW_GAP : 0)),
    )
    return {
        ...graph,
        nodes: graph.nodes.map((n) => {
            if (n.position) return n
            const column = depth.get(n.id) ?? 0
            const row = rows.get(column) ?? 0
            rows.set(column, row + 1)
            return {
                ...n,
                position: { x: column * COLUMN_GAP, y: top + row * ROW_GAP },
            }
        }),
    }
}

function commit(state: EditorState, graph: Graph, from = state.graph) {
    return {
        ...state,
        graph,
        past: [...state.past, from].slice(-HISTORY_LIMIT),
        future: [],
    }
}

function withPositions(
    graph: Graph,
    positions: Readonly<Record<string, NodePosition>>,
): Graph {
    const nodes = graph.nodes.map((n) => {
        const p = positions[n.id]
        if (!p || (n.position?.x === p.x && n.position.y === p.y)) return n
        return { ...n, position: { x: p.x, y: p.y } }
    })
    return nodes.some((n, i) => n !== graph.nodes[i])
        ? { ...graph, nodes }
        : graph
}

export function editorReducer(
    state: EditorState,
    action: EditorAction,
): EditorState {
    switch (action.type) {
        case 'move': {
            const graph = withPositions(state.graph, action.positions)
            const origin = state.dragOrigin ?? state.graph
            if (!action.done)
                return graph === state.graph
                    ? state
                    : { ...state, graph, dragOrigin: origin }
            const next = { ...state, dragOrigin: null }
            // A drag that ends where it started is no edit.
            if (samePositions(graph, origin)) return { ...next, graph: origin }
            return commit(next, graph, origin)
        }
        case 'select':
            return { ...state, selection: action.nodeIds }
        case 'undo': {
            const previous = state.past.at(-1)
            if (!previous || state.dragOrigin) return state
            return {
                ...state,
                graph: previous,
                past: state.past.slice(0, -1),
                future: [state.graph, ...state.future],
                selection: existing(state.selection, previous),
            }
        }
        case 'redo': {
            const next = state.future[0]
            if (!next || state.dragOrigin) return state
            return {
                ...state,
                graph: next,
                past: [...state.past, state.graph],
                future: state.future.slice(1),
                selection: existing(state.selection, next),
            }
        }
        case 'copy': {
            const ids = new Set(state.selection)
            if (ids.size === 0) return state
            return {
                ...state,
                clipboard: {
                    nodes: state.graph.nodes.filter((n) => ids.has(n.id)),
                    edges: state.graph.edges.filter(
                        (e) =>
                            ids.has(e.source_node_id) &&
                            ids.has(e.target_node_id),
                    ),
                },
            }
        }
        case 'paste': {
            const clip = state.clipboard
            if (!clip || state.dragOrigin) return state
            const id = (old: string) => {
                const fresh = action.ids[old]
                if (fresh === undefined) throw new Error(`no id for ${old}`)
                return fresh
            }
            const shift = (p: NodePosition | null) =>
                p && { x: p.x + PASTE_OFFSET, y: p.y + PASTE_OFFSET }
            const nodes = clip.nodes.map((n) => ({
                ...n,
                id: id(n.id),
                position: shift(n.position),
            }))
            const edges = clip.edges.map((e) => ({
                ...e,
                source_node_id: id(e.source_node_id),
                target_node_id: id(e.target_node_id),
            }))
            const graph = {
                nodes: [...state.graph.nodes, ...nodes],
                edges: [...state.graph.edges, ...edges],
            }
            return {
                ...commit(state, graph),
                selection: nodes.map((n) => n.id),
                // Pasting again lands one offset further, not on top.
                clipboard: { nodes, edges },
            }
        }
        case 'saved':
            // The undo stack survives a save (frontend/AGENTS §30).
            return { ...state, saved: action.graph, revision: action.revision }
    }
}

// Moves only change positions, so the node lists align index by index.
const samePositions = (a: Graph, b: Graph) =>
    a.nodes.every((n, i) => {
        const other = b.nodes[i]?.position
        return n.position?.x === other?.x && n.position?.y === other?.y
    })

const existing = (selection: string[], graph: Graph) =>
    selection.filter((id) => graph.nodes.some((n) => n.id === id))

/** A backend-shaped node id (`node_` + 32 hex digits). */
export const newNodeId = () => `node_${crypto.randomUUID().replaceAll('-', '')}`
